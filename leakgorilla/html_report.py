"""HTML report generator for LeakGorilla"""

from datetime import datetime
from collections import defaultdict


def generate_html_report(findings, output_file, target_url):
    """Generate a styled HTML report from findings"""
    by_severity = {'CRITICAL': [], 'HIGH': [], 'MEDIUM': [], 'LOW': []}
    for f in findings:
        by_severity[f.severity].append(f)

    severity_colors = {
        'CRITICAL': '#dc3545',
        'HIGH': '#fd7e14',
        'MEDIUM': '#ffc107',
        'LOW': '#17a2b8'
    }

    rows = ""
    for severity in ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW']:
        for f in by_severity[severity]:
            secret = f.matched_string
            redacted = secret[:4] + "..." + secret[-4:] if len(secret) > 8 else "***"
            color = severity_colors[severity]
            rows += f"""
            <tr>
                <td><span class="badge" style="background:{color}">{f.severity}</span></td>
                <td>{f.secret_type}</td>
                <td><a href="{f.url}" target="_blank">{f.url[:60]}...</a></td>
                <td>{f.source}</td>
                <td><code>{redacted}</code></td>
                <td><small>{f.context[:80]}...</small></td>
            </tr>"""

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>LeakGorilla Report - {target_url}</title>
    <style>
        * {{ margin: 0; padding: 0; box-sizing: border-box; }}
        body {{ font-family: 'Segoe UI', sans-serif; background: #0d1117; color: #c9d1d9; }}
        .header {{ background: #161b22; padding: 30px; border-bottom: 1px solid #30363d; }}
        .header h1 {{ color: #58a6ff; font-size: 2em; }}
        .header p {{ color: #8b949e; margin-top: 5px; }}
        .stats {{ display: flex; gap: 20px; padding: 20px 30px; background: #161b22; margin: 20px; border-radius: 8px; border: 1px solid #30363d; }}
        .stat {{ text-align: center; flex: 1; }}
        .stat .number {{ font-size: 2em; font-weight: bold; }}
        .stat .label {{ color: #8b949e; font-size: 0.9em; }}
        .critical {{ color: #dc3545; }}
        .high {{ color: #fd7e14; }}
        .medium {{ color: #ffc107; }}
        .low {{ color: #17a2b8; }}
        .container {{ padding: 20px 30px; }}
        table {{ width: 100%; border-collapse: collapse; background: #161b22; border-radius: 8px; overflow: hidden; border: 1px solid #30363d; }}
        th {{ background: #21262d; padding: 12px 15px; text-align: left; color: #8b949e; font-size: 0.85em; text-transform: uppercase; }}
        td {{ padding: 12px 15px; border-top: 1px solid #30363d; font-size: 0.9em; }}
        tr:hover {{ background: #1c2128; }}
        .badge {{ padding: 3px 8px; border-radius: 4px; color: white; font-size: 0.8em; font-weight: bold; }}
        code {{ background: #21262d; padding: 2px 6px; border-radius: 4px; font-family: monospace; }}
        a {{ color: #58a6ff; text-decoration: none; }}
        a:hover {{ text-decoration: underline; }}
        .footer {{ text-align: center; padding: 20px; color: #8b949e; font-size: 0.85em; }}
    </style>
</head>
<body>
    <div class="header">
        <h1>🦍 LeakGorilla Report</h1>
        <p>Target: {target_url} | Scanned: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} | Total Findings: {len(findings)}</p>
    </div>

    <div class="stats">
        <div class="stat">
            <div class="number critical">{len(by_severity['CRITICAL'])}</div>
            <div class="label">CRITICAL</div>
        </div>
        <div class="stat">
            <div class="number high">{len(by_severity['HIGH'])}</div>
            <div class="label">HIGH</div>
        </div>
        <div class="stat">
            <div class="number medium">{len(by_severity['MEDIUM'])}</div>
            <div class="label">MEDIUM</div>
        </div>
        <div class="stat">
            <div class="number low">{len(by_severity['LOW'])}</div>
            <div class="label">LOW</div>
        </div>
    </div>

    <div class="container">
        <table>
            <thead>
                <tr>
                    <th>Severity</th>
                    <th>Type</th>
                    <th>URL</th>
                    <th>Source</th>
                    <th>Value</th>
                    <th>Context</th>
                </tr>
            </thead>
            <tbody>
                {rows}
            </tbody>
        </table>
    </div>

    <div class="footer">
        Generated by LeakGorilla 🦍 | Author: Jeffrey Hawchab | https://github.com/jeffryhawchab/leakgorilla
    </div>
</body>
</html>"""

    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(html)

    print(f"\n✓ HTML report saved to {output_file}")
